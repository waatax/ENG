def get_cards():
    cards = []
    seen = set()

    # 1. Existing cards
    for word_clean, card_data in existing.items():
        if word_clean not in seen:
            seen.add(word_clean)
            cards.append(card_data)

    # 2. Add SAT Words
    for item in SAT_WORDS:
        if len(cards) >= 450:
            break
        w = item[0].strip().lower()
        if w not in seen:
            seen.add(w)
            idx = len(cards) + 1
            card = build_card(
                tier='sat',
                id_prefix='sa',
                index=idx,
                word=item[0],
                pos=item[1],
                zh=item[2],
                category=item[3]
            )
            cards.append(card)

    for i, c in enumerate(cards):
        c['id'] = f"fc-sa-{i+1:04d}"

    return cards[:450]

if __name__ == '__main__':
    c = get_cards()
    print(f"Generated Tier 5 (SAT) cards: {len(c)}")
    print(f"First card: {c[0]['id']} {c[0]['word']}")
    print(f"Last card: {c[-1]['id']} {c[-1]['word']}")
