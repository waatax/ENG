def get_cards():
    cards = []
    seen = set()

    # 1. Existing cards
    for word_clean, card_data in existing.items():
        if word_clean not in seen:
            seen.add(word_clean)
            cards.append(card_data)

    # 2. Add GMAT Words
    for item in GMAT_WORDS:
        if len(cards) >= 700:
            break
        w = item[0].strip().lower()
        if w not in seen:
            seen.add(w)
            idx = len(cards) + 1
            card = build_card(
                tier='gmat',
                id_prefix='gm',
                index=idx,
                word=item[0],
                pos=item[1],
                zh=item[2],
                category=item[3]
            )
            cards.append(card)

    for i, c in enumerate(cards):
        c['id'] = f"fc-gm-{i+1:04d}"

    return cards[:700]

if __name__ == '__main__':
    c = get_cards()
    print(f"Generated Tier 7 (GMAT) cards: {len(c)}")
    print(f"First card: {c[0]['id']} {c[0]['word']}")
    print(f"Last card: {c[-1]['id']} {c[-1]['word']}")
