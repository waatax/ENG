def get_cards():
    cards = []
    seen = set()

    # 1. Existing cards
    for word_clean, card_data in existing.items():
        if word_clean not in seen:
            seen.add(word_clean)
            cards.append(card_data)

    # 2. Add GRE Words
    for item in GRE_WORDS:
        if len(cards) >= 350:
            break
        w = item[0].strip().lower()
        if w not in seen:
            seen.add(w)
            idx = len(cards) + 1
            card = build_card(
                tier='gre',
                id_prefix='gr',
                index=idx,
                word=item[0],
                pos=item[1],
                zh=item[2],
                category=item[3]
            )
            cards.append(card)

    for i, c in enumerate(cards):
        c['id'] = f"fc-gr-{i+1:04d}"

    return cards[:350]

if __name__ == '__main__':
    c = get_cards()
    print(f"Generated Tier 6 (GRE) cards: {len(c)}")
